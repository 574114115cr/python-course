# comments.py —— 注释的三种写法

# 这是"整行注释"，写在单独一行，用来解释下面这段代码在干什么

age = 18  # 这是"行尾注释"，跟在代码后面，前面要有两个空格

# 注释可以很详细，也可以很简短。判断标准是：
# 三个月后你回来看，需要这段说明吗？需要就写。

# 不必要的注释反而是噪音，比如：
# print(age + 1)  # 打印年龄加一  ← 重复了代码本身的意思，属于废话注释

# 有价值的注释解释的是"为什么"，而不是"是什么"：
limit = 60  # 限制为 60 是因为需求文档规定单页最多 60 条

# 一个函数或类的开头用三引号写"文档字符串"，能被工具自动读取
"""
这个模块演示注释与文档字符串的写法。

文档字符串（docstring）用来描述模块、类或函数的用途，
写法是紧跟在它们下面的三引号字符串。
"""
print(age + 1)
