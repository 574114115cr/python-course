# print_demo.py —— print 的三个实用参数

# sep 指定"用什么把多个值隔开"
print("苹果", "香蕉", "橘子", sep="、")
# 输出：苹果、香蕉、橘子

# end 指定"这一行结束之后接什么"
print("正在加载", end="...")
print("完成")
# 输出：正在加载...完成（中间没有换行）

# 注释的三种写法
# 1）井号写在代码后面，前面要有两个空格才符合 PEP8
x = 1  # 这是行尾注释

# 2）单独成行的注释
# 这一整行都是说明文字

# 3）用三引号写"文档字符串"，常放在文件或函数开头
"""
这是模块级文档字符串。
说明这个文件是干什么的。
"""
