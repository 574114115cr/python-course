# practice.py —— 规范的变量命名与注释写法

# 这个文件用于练习"给变量起有意义的名字"

student_name = "王小美"          # 存学生的姓名（字符串）
student_age = 20# 存学生的年龄（整数）
enrollment_year = 2024  # 存入学年份（整数）

# 三条输出，分别展示三个变量
print("学生姓名：", student_name)
print("学生年龄：", student_age)
print("入学年份：", enrollment_year)

# 汇总三个变量，说明这个文件演示了什么
print("演示了如何用有意义的变量名加注释来记录学生信息。")
