# fstring_demo.py —— 格式化字符串，最常用的"拼句子"方式

name = "小红"
score = 92.567

# 普通做法：靠逗号隔开，输出会有多余空格
print("同学", name, "成绩", score)

# f-string 做法：大写 f 前缀，花括号里直接写变量名
print(f"同学{name}成绩{score}")

# 想控制小数位数，就在花括号里写 :.2f（保留两位小数）
print(f"同学{name}成绩{score:.2f}")

# 字符串里的对齐和补零也能做
num = 7
print(f"编号：{num:03d}")      # 03d 表示至少 3 位，不够前面补零 → 007
print(f"右对齐：{'hi':>8}|")     # >8 表示靠右，占 8 个字符宽度
print(f"左对齐：{'hi':<8}|")     # <8 表示靠左
print(f"居中对齐：{'hi':^8}|")  # ^8 表示居中
