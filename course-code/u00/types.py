# types.py —— 认识五种类型的判断

count = 10          # int
price = 19.9        # float
name = "李四"       # str
city = "杭州"       # str
is_vip = False      # bool

print(type(count), count)        # <class 'int'> 10
print(type(price), price)        # <class 'float'> 19.9
print(type(name), name)          # <class 'str'> 李四
print(type(city), city)          # <class 'str'> 杭州
print(type(is_vip), is_vip)      # <class 'bool'> False
