def slice_md(md, start, end):
    """按标题切取 md 片段：[start, end) ；end=None 表示到文件末。

    注意：讲义中代码块偶有缩进围栏（列表内嵌代码），必须strip 后再判断，
    否则围栏状态会错位，导致后面的标题被误判为在代码块内。
    """
    lines = md.split("\n")
    si = ei = None
    in_fence = False
    for i, ln in enumerate(lines):
        if ln.strip().startswith("```"):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        m = re.match(r"^(#{2,3}) (.+)$", ln)
        if not m:
            continue
        t = m.group(2).strip()
        if si is None and t.startswith(start):
            si = i
        elif si is not None and end and t.startswith(end):
            ei = i
            break
    if si is None:
        raise ValueError(f"起始标题未找到：{start!r}")
    if ei is None:
        if end:
            raise ValueError(f"结束标题未找到：{end!r}")
        ei = len(lines)
    return "\n".join(lines[si:ei]), "\n".join(lines[ei:ei + 200])


def main():
    os.makedirs(OUT, exist_ok=True)
    # 111 个课节页共用一份 CSS（约 10 KB/页）：写成外链文件，页面只留结构
    open(os.path.join(OUT, "lessons.css"), "w",
         encoding="utf-8").write(lt.CSS)
    md_cache = {}

    # 先建完整清单，供每页侧栏导航使用
    meta = []
    for idx, (u, _rng, week, title, goal, live, hw) in enumerate(LESSONS):
        meta.append(dict(no=idx + 1, unit=u, week=week, title=title, goal=goal,
                         live=live, hw=hw, file=f"{idx + 1:02d}.html",
                         sections=[]))

    total = len(LESSONS)
    for idx, (u, (start, end), week, title, goal, live, hw) in enumerate(LESSONS):
        fname = next(f for f in os.listdir(COURSE)
                     if f.startswith(f"{u:02d}-"))
        if fname not in md_cache:
            md_cache[fname] = open(os.path.join(COURSE, fname), encoding="utf-8").read()
        md = md_cache[fname]

        frag, rest = slice_md(md, start, end)
        if not frag.strip():
            print(f"  !! 第 {idx+1} 节切片为空：{fname} [{start} -> {end}]")
        body = bl.add_heading_ids(bl.convert(frag))
        ntoc = len(re.findall(r'<h[23] id="', body))
        # 记录本节所有小节标题，供课程目录页做「按内容搜索」
        meta[idx]["sections"] = [re.sub(r"<[^>]+>", "", t).strip()
                                 for t in re.findall(r'<h[23] id="[^"]+">(.*?)</h[23]>',
                                                     body, re.S)]

        n = idx + 1
        prev_link = (LESSONS[idx - 1], n - 1) if idx > 0 else None
        next_link = (LESSONS[idx + 1], n + 1) if idx < total - 1 else None

        # 阶段 1 用 recaps.py / reviews.py，阶段 2 用 recaps_stage2.py
        stage2 = (u >= 12)
        R = rc2 if stage2 else rc
        V = rc2 if stage2 else rv

        # 复盘：每阶段第一节讲上课方式，其余回顾上一节要点
        first_of_stage = (n == 1) or (n == 65)
        if first_of_stage:
            recap_head = ("阶段 2 开课准备（10 分钟）｜这 47 节课怎么上"
                          if stage2 else "开课准备（10 分钟）｜这节课怎么上")
            recap_items = R.OPENING
        else:
            prev_title = LESSONS[idx - 1][3]
            recap_head = f"复盘（10 分钟）｜上一节：第 {n-1} 节 · {prev_title}"
            recap_items = R.RECAP.get(n)
        if not recap_items:
            raise ValueError(f"第 {n} 节缺少复盘内容")

        # 讲评：检查本节实操写出来的代码，附一句话总结
        rv_lesson = V.REVIEWS.get(n)
        if not rv_lesson or not rv_lesson.get("items"):
            raise ValueError(f"第 {n} 节缺少讲评内容")

        page = lt.lesson_page(n, total, u, week, title, goal, live, hw,
                              body, prev_link, next_link, meta,
                              recap_head=recap_head, recap_items=recap_items,
                              review_items=rv_lesson["items"],
                              review_summary=rv_lesson.get("summary"))
        fp = os.path.join(OUT, f"{n:02d}.html")
        open(fp, "w", encoding="utf-8").write(page)
        print(f"  第 {n:02d} 节 · 单元{u:02d} · {title}  (目录 {ntoc} 项, {len(page)//1024} KB)")

    idx_html = lt.index_page(meta)
    open(os.path.join(OUT, "index.html"), "w", encoding="utf-8").write(idx_html)

    # 复习计划页：按艾宾浩斯曲线给全部课节排 6 轮复习（数据来自 lesson-done-v1 时间戳）
    rv_html = lt.review_page(meta)
    open(os.path.join(ROOT, "web", "review.html"), "w", encoding="utf-8").write(rv_html)
    print(f"  复习计划页：web/review.html（{len(meta)} 节 × {len(lt.REVIEW_STAGES)} 轮）")

    by_unit = {}
    for m in meta:
        by_unit.setdefault(m["unit"], []).append(m)
    print(f"\n共生成 {len(meta)} 节课，覆盖 {len(by_unit)} 个单元")
    for u in sorted(by_unit):
        ls = by_unit[u]
        print(f"  单元 {u:>2} · {lt.UNIT_TITLE[u]:<22} {len(ls)} 节  ({', '.join(l['week'] for l in ls)})")
    print(f"输出：{OUT}")


